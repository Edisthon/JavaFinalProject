    private void btnSubmitStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitStatusActionPerformed
            String selectedItem = (String) comboProductId.getSelectedItem();
    if (selectedItem == null || selectedItem.equals("List of product IDs")) {
        JOptionPane.showMessageDialog(this, "Please select a valid Product ID.");
        return;
    }
    int productId = Integer.parseInt(selectedItem);
    String location = txtLocation.getText().trim();
    String tempStr = txtTemperature.getText().trim();
    String humStr = txtHumidity.getText().trim();

    if (location.isEmpty() || tempStr.isEmpty() || humStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields!", "Input Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        double temperature = Double.parseDouble(tempStr);
        double humidity = Double.parseDouble(humStr);

        ProductStatusLog log = new ProductStatusLog();
        log.setProductId(productId);
        log.setLocation(location);
        log.setTemperature(temperature);
        log.setHumidity(humidity);     

       

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Temperature and humidity must be numbers.", "Input Error", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnSubmitStatusActionPerformed

