    private void allowOnlyLettersLoc(JTextField textField) {
    txtLocation.addKeyListener(new java.awt.event.KeyAdapter() {
        public void keyTyped(java.awt.event.KeyEvent evt) {
            char c = evt.getKeyChar();
            if (!Character.isLetter(c) && !Character.isWhitespace(c)) {
                evt.consume();
                JOptionPane.showMessageDialog(null, "Only alphabets allowed");
            }
        }
    });
    }
    
    private void allowOnlyNumbersTemp(JTextField textField) {
    txtTemperature.addKeyListener(new java.awt.event.KeyAdapter() {
        public void keyTyped(java.awt.event.KeyEvent evt) {
            char c = evt.getKeyChar();
            String currentText = textField.getText();

            if (!Character.isDigit(c) && c != '.') {
                evt.consume();
                JOptionPane.showMessageDialog(null, "Only digits and decimal point allowed");
            }

            if (c == '.' && currentText.contains(".")) {
                evt.consume();
                JOptionPane.showMessageDialog(null, "No more than one decimal point allowed");
            }

            if (currentText.isEmpty() && c == '.') {
                evt.consume();
                JOptionPane.showMessageDialog(null, "Starting with a decimal point is not allowed");
            }
        }
    });
    }


    
